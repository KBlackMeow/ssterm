Uint8List buildTable() {
  final table = Uint8List(65536);
  table.fillRange(0, table.length, 1);
  table[0] = 0;
  table.fillRange(1, 32, 0);
  table.fillRange(0x7f, 0xa0, 0);
  for (var r = 0; r < BMP_COMBINING.length; ++r) {
    table.fillRange(BMP_COMBINING[r][0], BMP_COMBINING[r][1] + 1, 0);
  }
  for (var r = 0; r < BMP_WIDE.length; ++r) {
    table.fillRange(BMP_WIDE[r][0], BMP_WIDE[r][1] + 1, 2);
  }
  return table;
}

bool bisearch(int ucs, List<List<int>> data) {
  var min = 0;
  var max = data.length - 1;
  int mid;
  if (ucs < data[0][0] || ucs > data[max][1]) {
    return false;
  }
  while (max >= min) {
    mid = (min + max) >> 1;
    if (ucs > data[mid][1]) {
      min = mid + 1;
    } else if (ucs < data[mid][0]) {
      max = mid - 1;
    } else {
      return true;
    }
  }
  return false;
}

class UnicodeV11 {
  /// The underlying table began at Unicode 11; width deltas below bring its
  /// terminal semantics through Unicode 16 without a runtime dependency.
  final version = '16';

  int wcwidth(int codePoint) {
    if (codePoint < 32) return 0;
    if (codePoint < 127) return 1;
    if (bisearch(codePoint, UNICODE16_ZERO_WIDTH_DELTA)) return 0;
    if (bisearch(codePoint, UNICODE16_NARROW_DELTA)) return 1;
    if (bisearch(codePoint, UNICODE16_WIDE_DELTA)) return 2;
    // Unicode 11's East Asian-width table predates the current convention for
    // text-presentation emoji. Modern terminal UIs (including ChatCode) lay
    // these symbols out as two cells even when they are emitted without VS16.
    // A one-cell result makes cursor-addressed incremental redraws miss a
    // cell, leaving a character from the previous frame behind.
    if (_isModernEmojiDoubleWidth(codePoint)) return 2;
    if (codePoint < 65536) return table[codePoint];
    if (bisearch(codePoint, HIGH_COMBINING)) return 0;
    if (bisearch(codePoint, HIGH_WIDE)) return 2;
    return 1;
  }

  /// Pre-Unicode-12 semantics: the historical table alone, without the
  /// emoji-presentation or Unicode 16 delta rules. Escape hatch for legacy
  /// apps whose layout predates wide emoji (iTerm2's older "Unicode version"
  /// profiles serve the same purpose).
  int wcwidthLegacy(int codePoint) {
    if (codePoint < 32) return 0;
    if (codePoint < 127) return 1;
    if (codePoint < 65536) return table[codePoint];
    if (bisearch(codePoint, HIGH_COMBINING)) return 0;
    if (bisearch(codePoint, HIGH_WIDE)) return 2;
    return 1;
  }
}

/// Whether [codePoint] is Extended_Pictographic (UTS#51). These are the
/// characters whose presentation — and therefore terminal cell width — can
/// be changed by a following VS16/VS15 variation selector.
bool isExtendedPictographic(int codePoint) {
  return bisearch(codePoint, EXTENDED_PICTOGRAPHIC);
}

/// Whether [codePoint] has East_Asian_Width=A (ambiguous). Terminals disagree
/// on whether ambiguous characters occupy one or two cells; hosts expose this
/// as a setting (iTerm2: "Ambiguous Double Width").
bool isAmbiguousWidth(int codePoint) {
  return bisearch(codePoint, AMBIGUOUS_WIDTH);
}

